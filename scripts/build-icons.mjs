// Extracts the game-icons.net icons we use into a small generated module,
// so the 6 MB icon set never reaches the bundle. Run: npm run icons
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const set = JSON.parse(readFileSync(require.resolve("@iconify-json/game-icons/icons.json"), "utf8"));

const NAMES = [
  // weapons & armour
  "wood-stick", "sewing-needle", "plain-dagger", "broadsword", "battle-axe", "flanged-mace", "claw-hammer",
  "war-pick", "spear-feather", "warhammer", "spear-hook", "pirate-hook", "sling", "pocket-bow",
  "stone-pile", "quiver", "leather-armor", "breastplate",
  // essentials
  "torch", "old-lantern", "light-bulb", "cheese-wedge", "mushroom", "shiny-purse", "rune-stone", "knapsack",
  // conditions
  "sleepy", "terror", "stomach", "broken-bone", "brain-leak", "hazard-sign",
  // ui
  "crossed-swords", "dice-twenty-faces-twenty", "campfire", "hearts", "sparkles",
  // creatures (NPC medallions)
  "cat", "owl", "frog", "toad-teeth", "spider-face", "centipede", "snake", "raven", "rat", "scarab-beetle",
  "fairy", "ghost", "bat", "fox-head", "earth-worm", "hood", "bee", "ant", "hedgehog", "lizard-tongue",
  "squirrel", "rabbit-head", "mole", "dragonfly", "snail", "butterfly", "heron", "badger", "cultist",
  "wizard-face", "crown",
  // time & weather
  "sun", "moon", "sunrise", "sunset", "night-sky", "raining", "snowing", "sun-cloud", "falling-leaf",
  "flowers", "hourglass", "footprint", "cave-entrance", "whirlwind",
  // map
  "high-grass", "pine-tree", "waves", "house", "mushroom-house", "position-marker", "treasure-map", "paint-brush", "eye-target",
];

const size = set.width ?? 512;
const out = {};
for (const name of NAMES) {
  const icon = set.icons[name];
  if (!icon) throw new Error(`Icon "${name}" not found in game-icons`);
  // Drop the opaque background square game-icons ships with, keep the glyph.
  out[name] = icon.body.replace(/<path d="M0 0h512v512H0z"\/>/, "");
}

writeFileSync(
  new URL("../src/client/icons.gen.ts", import.meta.url),
  `// Generated by scripts/build-icons.mjs from game-icons.net (CC BY 3.0). Do not edit.\n` +
    `export const ICON_SIZE = ${size};\n` +
    `export const ICONS = ${JSON.stringify(out, null, 1)} as const;\n` +
    `export type IconName = keyof typeof ICONS;\n`,
);
console.log(`Wrote ${NAMES.length} icons.`);
